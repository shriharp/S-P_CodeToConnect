def _fill(template: str) -> str:
    import re

    c = random.choice(COMPANIES)
    return template.format(
        c=c,
        f=random.choice(FIGURES),
        o=random.choice(OBJECTS),
        p=random.choice(PLANTS),
    ).replace("  ", " ")


def main(per_category: int = 220) -> None:
    random.seed(42)
    held_out = {t for t, _ in EVENT_EVAL_CASES}
    rows: list[dict] = []
    for label, templates in TEMPLATES.items():
        for i in range(per_category):
            text = _fill(random.choice(templates))
            # Light lexical jitter so the same template yields varied surface forms.
            if i % 3 == 1:
                text = text.replace(" the ", " a ", 1)
            if i % 5 == 2:
                text = text.lower()
            if text in held_out:
                continue  # never train on an eval case
            rows.append({"text": text, "label": label})
    random.shuffle(rows)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r) + "\n")
    from collections import Counter

    counts = Counter(r["label"] for r in rows)
    print(f"wrote {len(rows)} training rows -> {OUT}")
    print("per-label:", dict(counts))


if __name__ == "__main__":
    main()
